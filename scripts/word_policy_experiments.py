import sys
from pathlib import Path

REPOSITORY = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPOSITORY))

from scripts.word_policy.data import load
from scripts.word_policy.evaluate import evaluate

FLAGS = ("proper_noun", "acronym", "letter_names", "abbreviation", "loan", "unusual_spelling")
OUTPUT = REPOSITORY.parent / "notes/issue-10-phonograms/word-policy/experiments.md"


def special(limit: int, **extra) -> dict:
    return {**{flag: limit for flag in FLAGS}, **extra}


POLICIES = {
    "Everything": {},
    "Remove names-only": {"proper_noun": 0},
    "Remove names, acronyms, abbreviations, letter names": {"proper_noun": 0, "acronym": 0, "abbreviation": 0, "letter_names": 0},
    "Also remove loanwords": special(0, unusual_spelling=None),
    "Also remove unusual spellings": special(0),
    "Special words only if in the top 5,000": special(5000),
    "Special words only if in the top 10,000": special(10000),
    "Only the 30,000 most frequent words": {"maximum_rank": 30000},
    "Rare phonograms (under 15 words) removed, top 3,000 protected": {"rare_phonogram_min": 15, "keep_top": 3000},
    "Balanced: specials in top 5,000, rare phonograms under 15, top 5,000 protected": special(5000, rare_phonogram_min=15, keep_top=5000),
    "Elementary: specials in top 3,000, 30,000 cap, rare under 15, top 3,000 protected": special(3000, maximum_rank=30000, rare_phonogram_min=15, keep_top=3000),
}


def table() -> str:
    data = load()
    rows = ["| Policy | Words | Reading kept | Phonograms | Rare (under 15 words) | Odd (not in lessons) | Words with a rare phonogram |", "|---|---:|---:|---:|---:|---:|---:|"]
    for name, policy in POLICIES.items():
        result = evaluate(data, {key: value for key, value in policy.items() if value is not None})
        rows.append(f"| {name} | {result['words']:,} | {result['usage']:.1%} | {result['concepts']} | {result['rare']} | {result['unmodeled']} | {result['in_rare']:,} |")
    return "\n".join(rows) + "\n"


def main() -> None:
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    text = "# Word list policy experiments\n\nGenerated by `make word-policy-experiments`. Phonograms are lesson phonograms plus observed patterns with no lesson definition.\n\n" + table()
    OUTPUT.write_text(text)
    print(text)


if __name__ == "__main__":
    main()
