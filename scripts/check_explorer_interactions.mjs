assert(q('#we-detail .pg-het'), 'heteronym flag shows');
assert(!q('#we-detail .pg-het-details'), 'details start closed');
q('#we-detail .pg-het').click();
assert(q('#we-detail .pg-het-details .pg-senses li'), 'click opens the meanings');
assert.equal(all('#we-detail .pg-pron').length, 2, 'both pronunciations shown');
const before = q('#we-detail .pg-breakdown').textContent;
q('#we-detail .pg-pron:nth-child(2)').click();
assert(q('#we-detail .pg-pron.active:nth-child(2)'), 'second pronunciation becomes active');
assert.notEqual(q('#we-detail .pg-breakdown').textContent, before, 'breakdown follows the pronunciation');
assert(q('#we-detail-panel').classList.contains('open'), 'panel stays open');
