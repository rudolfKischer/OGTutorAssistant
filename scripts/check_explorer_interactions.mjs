import {createRequire} from 'node:module';
import assert from 'node:assert/strict';
const root = new URL('../..', import.meta.url).pathname.replace(/\/$/, '');
const require = createRequire(`${root}/DecodifyWebsite/package.json`);
const {JSDOM} = require('jsdom');
const base = process.argv[2] || 'http://127.0.0.1:5003';
const pause = (ms = 600) => new Promise(resolve => setTimeout(resolve, ms));
const dom = await JSDOM.fromURL(`${base}/#word-view`, {
  runScripts: 'dangerously', resources: 'usable', pretendToBeVisual: true,
  beforeParse(window) { window.fetch = url => fetch(new URL(url, base)); window.HTMLElement.prototype.scrollIntoView = () => {}; }
});
const w = dom.window;
await pause(2500);
const q = selector => w.document.querySelector(selector);
const all = selector => [...w.document.querySelectorAll(selector)];
const features = () => [...w.eval('weFeatures')];
assert(all('#we-board .pg-card').length > 100, 'phonogram cards render');
assert(!all('button').some(button => /play/i.test(button.textContent)), 'no play button');
assert.equal(all('#we-controls .pg-seg').length, 6, 'mode and lens segments');
q('#we-board .pg-u-g[data-token="g:ea"]').click();
assert.deepEqual(features(), ['g:ea'], 'grapheme region selects the grapheme');
q('#we-board .pg-s[data-token="p:short_e"]').click();
assert.deepEqual(features(), ['g:ea', 'p:short_e'], 'phoneme region selects the phoneme');
const card = q('#we-board .pg-card[data-token="phonogram_ea_long_e"]');
card.click();
assert(features().includes('phonogram_ea_long_e'), 'card selects the phonogram');
w.eval('weClearAll()');
w.eval("weSetLens('graphemes')"); 
assert(all('#we-board .pg-card[data-token^="g:"]').length > 50, 'grapheme lens');
w.eval("weSetLens('phonemes')");
assert(all('#we-board .pg-card[data-token^="p:"]').length > 30, 'phoneme lens');
q('#we-board .pg-card[data-token="p:short_e"]').click();
w.eval("weSetLens('phonograms')");
assert(q('#we-board .pg-s.sel[data-token="p:short_e"]'), 'selected phoneme highlights inside phonogram cards');
assert(!q('#we-selection').hidden, 'selection tray shows while selected');
assert.equal(all('#we-selection .pg-chip').length, 1, 'one chip per selected item');
q('#we-selection .pg-chip').click();
assert.equal(features().length, 0, 'chip removes its item');
assert(!q('#we-selection').hidden && q('#we-selection .pg-sel-empty'), 'tray stays in place with a hint when empty');
q('#we-board .pg-u-g[data-token="g:ea"]').click();
q('#we-board .pg-s[data-token="p:short_e"]').click();
assert.equal(all('#we-selection .pg-chip').length, 2, 'two chips');
q('#we-clear').click();
assert.equal(features().length, 0, 'clear removes selection');
w.eval("weOpenDetail('make')");
await pause(800);
q('#we-detail .pg-bd-g[data-token="g:a_e"]').click();
await pause(800);
assert.deepEqual(features(), ['g:a_e'], 'detail click selects the grapheme');
assert(q('#we-detail-panel').classList.contains('open'), 'detail stays open after selecting');
assert.equal(q('#we-detail h2').textContent.trim(), 'make', 'same word still shown');
assert(q('#we-detail .pg-bd-g.sel[data-token="g:a_e"]'), 'detail shows the selection');
q('#we-detail .pg-s[data-token="p:long_a"]').click();
assert.deepEqual(features(), ['g:a_e', 'p:long_a']);
q('#we-detail .pg-bd-unit[data-token="phonogram_m_m"]').click();
assert(features().includes('phonogram_m_m'), 'unit padding selects the phonogram');
assert(q('#we-detail .pg-bd-unit.selected[data-token="phonogram_m_m"]'), 'selected phonogram looks selected in the word panel');
assert(!q('#we-detail .pg-bd-unit.selected[data-token="phonogram_k_k"]'), 'unselected phonogram does not');
assert(!q('#we-rf-origin-wrap .pg-tags'), 'tags dropdown starts closed');
q('#we-origin-toggle').click();
assert.equal(all('#we-rf-origin-wrap .pg-tag').length, 11, 'one chip per tag including heteronyms');
assert(q('.pg-tag[data-flag="heteronym"]'), 'heteronym tag exists');
assert(!all('#we-rf-origin-wrap button').some(button => /match/i.test(button.textContent)), 'no match all link');
q('.pg-tag[data-flag="loan"]').click();
assert(q('.pg-tag[data-flag="loan"].on'), 'a click selects the tag');
assert.equal(w.eval('weOriginFilterValue()'), 'loan');
q('.pg-tag[data-flag="heteronym"]').click();
assert.equal(w.eval('weOriginFilterValue()'), 'loan,heteronym');
q('#we-rf-origin-wrap [data-without="true"]').click();
assert.equal(w.eval('weOriginFilterValue()'), 'not_loan,not_heteronym', 'Without turns the selection into exclusions');
assert.equal(w.eval('weOriginMode()'), '');
q('#we-rf-origin-wrap [data-without="false"]').click();
assert.equal(w.eval('weOriginMode()'), 'any', 'With shows words that have any selected tag');
q('.pg-tag[data-flag="loan"]').click();
q('.pg-tag[data-flag="heteronym"]').click();
assert.equal(w.eval('weOriginFilterValue()'), '', 'a second click deselects');
q('#we-origin-toggle').click();
assert(!q('#we-rf-origin-wrap .pg-tags'), 'tags dropdown closes');
assert(q('#we-settings-button'), 'settings button exists');
assert(q('#we-settings').hidden, 'settings panel starts closed');
q('#we-settings-button').click();
await pause(1500);
assert(!q('#we-settings').hidden, 'settings panel opens');
assert.equal(all('#we-settings .pg-set-presets .pg-seg').length, 3, 'three presets');
assert.equal(all('#we-settings [data-category="names"]').length, 3, 'three choices per category');
assert.equal(all('#we-settings .pg-set-heads span').length, 3, 'column labels appear once');
assert.equal(all('#we-settings .pg-pill').length, 5, 'one pill slider per graded special word kind');
assert.equal(all('#we-settings .pg-switch').length, 1, 'inappropriate words use an on/off switch');
const pillCell = q('#we-settings [data-category="loans"][data-mode="remove"]');
assert(pillCell, 'pill cells exist');
const tipTarget = q('#we-settings [data-tip]');
tipTarget.dispatchEvent(new w.MouseEvent('mouseover', { bubbles: true }));
await pause(400);
assert(q('#we-tip.show') && q('#we-tip').textContent.length > 5, 'hovering shows a tip');
tipTarget.dispatchEvent(new w.MouseEvent('mouseout', { bubbles: true }));
await pause(100);
assert(!q('#we-tip.show'), 'tip hides when the pointer leaves');
pillCell.click();
assert.equal(q('#we-settings [data-pill="loans"]').dataset.mode, 'remove', 'clicking a pill third selects it');
assert.equal(q('#we-settings [data-pill="loans"]').style.getPropertyValue('--index'), '2', 'thumb moves to the third position');
q('#we-settings [data-category="loans"][data-mode="keep"]').click();
assert(!all('#we-settings button').some(button => /^Only common$/.test(button.textContent)), 'choice labels are not repeated per row');
assert.equal(all('#we-settings input[type=range]').length, 4, 'four sliders');
assert(!q('#we-settings input[type=number]'), 'no number boxes');
assert(q('#we-settings-save').disabled, 'save is disabled until something changes');
q('#we-settings [data-switch="safety"]').click();
assert.equal(q('#we-settings [data-switch="safety"]').getAttribute('aria-checked'), 'true', 'the switch turns on');
assert(!q('#we-settings-save').disabled, 'the switch counts as a change');
q('#we-settings [data-switch="safety"]').click();
assert.equal(q('#we-settings [data-switch="safety"]').getAttribute('aria-checked'), 'false', 'the switch turns off again');
await pause(1500);
assert(q('#we-settings-save').disabled, 'back to the saved state');
q('#we-settings [data-preset="balanced"]').click();
await pause(6000);
assert(!q('#we-settings-save').disabled, 'save enables after a change');
assert(q('#we-settings-unsaved').textContent.length > 0, 'unsaved changes are announced');
assert(!q('#we-settings-button').classList.contains('active'), 'nothing is applied before saving');
assert(!w.eval("weBuildParams().get('policy')"), 'searches ignore unsaved changes');
assert(q('#we-settings [data-stat="words"]').textContent.startsWith('56,'), 'preview shows the draft result');
assert(q('#we-settings [data-sub="words"]').textContent.includes('67,423'), 'totals give context');
q('#we-settings-cancel').click();
assert(q('#we-settings').hidden, 'cancel closes the panel');
q('#we-settings-button').click();
await pause(800);
assert(q('#we-settings-save').disabled, 'cancelled changes are discarded');
q('#we-settings [data-preset="balanced"]').click();
q('#we-settings-save').click();
await pause(6000);
assert(q('#we-settings').hidden, 'save closes the panel');
assert(q('#we-settings-button').classList.contains('active'), 'saved filter is applied');
assert(w.eval("weBuildParams().get('policy')"), 'searches carry the saved policy');
q('#we-settings-button').click();
await pause(800);
q('#we-settings-reset').click();
q('#we-settings-save').click();
await pause(2500);
assert(!q('#we-settings-button').classList.contains('active'), 'reset and save clears the filter');
const cardsBefore = all('#we-board .pg-card').length;
q('#we-settings-button').click();
await pause(800);
q('#we-settings [data-preset="strict"]').click();
q('#we-settings-save').click();
await pause(8000);
assert(all('#we-board .pg-card').length < cardsBefore, 'phonograms with no words disappear once the policy is saved');
assert(!all('#we-board .we-row-toggle').some(toggle => /lesson definition/.test(toggle.textContent)), 'tail toggles are short');
assert(all('#we-board .we-row-toggle').some(toggle => /^\+\d+ extra$/.test(toggle.textContent)), 'extra spellings read as +N extra');
const cardsFiltered = all('#we-board .pg-card').length;
w.eval("weOpenDetail('sex')");
await pause(1200);
assert(/hidden by your word list settings/.test(q('#we-detail').textContent), 'a removed word cannot be looked up');
w.eval("weOpenDetail('dog')");
await pause(1200);
assert.equal(q('#we-detail h2').textContent.trim(), 'dog', 'other words still open');
w.eval("weOpenDetail('make')");
await pause(1200);
for (const mode of ['any', 'all', 'only']) {
  w.eval(`weSetMode('${mode}')`);
  q('#we-board .pg-card[data-token="phonogram_ea_long_e"], #we-board .pg-card').click();
  await pause(3500);
  assert(all('#we-board .pg-card').length <= cardsFiltered, `selecting a concept in ${mode} mode never brings back phonograms the settings removed`);
  w.eval('weClearAll()');
  await pause(2500);
}
w.eval("weSetMode('any')");
q('#we-settings-button').click();
await pause(800);
q('#we-settings-reset').click();
q('#we-settings-save').click();
await pause(3500);
assert.equal(all('#we-board .pg-card').length, cardsBefore, 'resetting brings every phonogram back');
