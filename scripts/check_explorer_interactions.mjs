assert(!q('.pg-pop'), 'popover closes on outside click');
assert(!q('#we-detail .pg-bd-controls'), 'no breakdown selector');
assert(q('#we-detail .pg-bd-unit[data-token="phonogram_a_e_long_a"]'), 'split vowel unit');
