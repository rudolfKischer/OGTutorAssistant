assert(q('.pg-pop'), 'display popover opens');
assert.equal(all('.pg-opt').length, 3, 'three notations');
q('.pg-opt:nth-child(3)').click();
assert(q('#we-board .pg-s').textContent.includes('/'), 'notation changes the board');
